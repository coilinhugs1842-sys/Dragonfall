const HIT_STORM: readonly EmitterRecipe[] = [RECIPES.stormBite];

/**
 * The burst where damage landed. `attackerClass` is null when the attacker is unknown or the
 * environment did it. The class decides the shape, the caller scales it by the damage.
 */
export function hitEffectFor(
  source: DamageSource,
  attackerClass: DragonClassId | null,
): readonly EmitterRecipe[] {
  if (source === 'terrain') return HIT_TERRAIN;
  if (source === 'storm') return HIT_STORM;
  if (attackerClass === 'tempest') return HIT_LIGHTNING;
  if (attackerClass === 'wraith') return HIT_SHADE;
  return HIT_DEFAULT;
}

/** Damage that gives a full-size hit burst; smaller hits (damage over time) shrink toward... */
export const HIT_FULL_DAMAGE = 20;
/** ...this fraction of the size and count, larger ones grow up to HIT_MAX_SCALE. */
export const HIT_MIN_SCALE = 0.35;
export const HIT_MAX_SCALE = 1.8;

export function hitScale(damage: number): number {
  const scale = damage / HIT_FULL_DAMAGE;
  return scale < HIT_MIN_SCALE ? HIT_MIN_SCALE : scale > HIT_MAX_SCALE ? HIT_MAX_SCALE : scale;
}

