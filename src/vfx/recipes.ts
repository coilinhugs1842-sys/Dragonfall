/** How a zone is hinted at: a shell, and sparse particles inside it. */
export interface ZoneStyle {
  /** Shell brightness; 0 = no shell. */
  readonly shell: number;
  readonly shellColor: ColorRole;
  readonly rimPower: number;
  /** Streams inside the zone, spawned within `interiorRadius` of the zone radius. */
  readonly interior: readonly EmitterRecipe[];
  readonly interiorRadius: number;
  /** The interior is centred this fraction of the radius above the zone centre. */
  readonly interiorLift: number;
  /** Bursts at the centre when the zone first appears. */
  readonly appear: readonly EmitterRecipe[];
  /** Idle lightning strikes per second inside it. */
  readonly flickerPerS: number;
}

