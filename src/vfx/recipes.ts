/** What plays when an ability fires. */
export interface CastEffect {
  /** Bursts at the muzzle (or the dragon's centre), aimed along the cast direction. */
  readonly bursts: readonly EmitterRecipe[];
  /** True: at the dragon's centre instead of in front of its nose. */
  readonly centred: boolean;
  /** A beam from the muzzle along the aim, as long as the ability's range. */
  readonly beam: BeamStyle | null;
}

const cast = (
  bursts: readonly EmitterRecipe[],
  centred = false,
  beam: BeamStyle | null = null,
): CastEffect => ({ bursts, centred, beam });

