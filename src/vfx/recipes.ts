const ALIGN = 0.0001;

// --- Shared pieces -------------------------------------------------------------------------------

const flash = (size: number, life: number, intensity: number): EmitterRecipe =>
  defineRecipe({
    sprite: SPRITE_DOT,
    count: 1,
    minCount: 1,
    lifeMin: life,
    lifeMax: life * 1.15,
    sizeMin: size,
    sizeMax: size * 1.1,
    sizeEnd: 1.9,
    colorStart: COLOR_HOT,
    colorEnd: COLOR_TEAM,
    inherit: 1,
    intensityStart: 1 + (intensity - 1) * 0.35,
    intensityEnd: intensity * 0.25,
    fadeIn: 0,
    fadeOut: 0.15,
  });

const ring = (
  size: number,
  grow: number,
  life: number,
  color: ColorRole,
  intensity: number,
  count = 1,
): EmitterRecipe =>
  defineRecipe({
    sprite: SPRITE_RING,
    count,
    minCount: 1,
    lifeMin: life,
    lifeMax: life * 1.25,
    sizeMin: size,
    sizeMax: size * 1.15,
    sizeEnd: grow,
    colorStart: color,
    colorEnd: color === COLOR_HOT || color === COLOR_GLOW ? COLOR_TEAM : color,
    inherit: 1,
    intensityStart: 1 + (intensity - 1) * 0.35,
    intensityEnd: intensity * 0.5,
    opacity: 0.5,
    fadeIn: 0.05,
    fadeOut: 0.2,
  });

